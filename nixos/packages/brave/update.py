#!/usr/bin/env python3
# 把 brave.nix 更新到 Brave 最新稳定版（改自 nixpkgs 原来的 update.py，去掉了 Brave Origin）。
import base64
import os
import urllib.request

DOWNLOAD_URLS = {
    "aarch64-linux": "https://github.com/brave/brave-browser/releases/download/v${version}/brave-browser_${version}_arm64.deb",
    "x86_64-linux": "https://github.com/brave/brave-browser/releases/download/v${version}/brave-browser_${version}_amd64.deb",
    "aarch64-darwin": "https://github.com/brave/brave-browser/releases/download/v${version}/Brave-Browser-arm64.dmg",
}


def wget(url):
    res = urllib.request.urlopen(url)
    assert res.code == 200
    return res.read().decode("ascii")


def sha256_to_sri(hash):
    return "sha256-" + base64.b64encode(bytes.fromhex(hash)).decode("utf-8")


def get_version():
    # 各平台的版本号必须一致。
    versions = set(
        wget(f"https://versions.brave.com/latest/{p}.version").strip()
        for p in ["release-linux-arm64", "release-linux-x64", "release-macos-arm64"]
    )
    assert len(versions) == 1, versions
    return versions.pop()


def main():
    os.chdir(os.path.dirname(os.path.abspath(__file__)))
    version = get_version()
    print(f"brave -> {version}")
    lines = [
        "# Expression generated by update.py; do not edit it by hand!",
        "rec {",
        '  pname = "brave";',
        f'  version = "{version}";',
        "",
        "  archives = {",
    ]
    for arch, url in DOWNLOAD_URLS.items():
        hash = sha256_to_sri(wget(url.replace("${version}", version) + ".sha256").split(" ")[0])
        lines += [f"    {arch} = {{", f'      url = "{url}";', f'      hash = "{hash}";', "    };"]
    lines += ["  };", "}"]
    with open("brave.nix", "w") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
